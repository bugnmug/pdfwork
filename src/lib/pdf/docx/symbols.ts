const WEBDINGS: Record<number, string> = { 0x3d: "☐", 0x61: "✓", 0x72: "✗", 0x6e: "■", 0x63: "□" };

const TABLES: [RegExp, Record<number, string>][] = [
  [/^symbol$/i, SYMBOL],
  [/^wingdings$/i, WINGDINGS],
  [/^wingdings 2$/i, WINGDINGS2],
  [/^wingdings 3$/i, WINGDINGS3],
  [/^webdings$/i, WEBDINGS],
];

export function isSymbolFont(font: string | undefined): boolean {
  return !!font && TABLES.some(([re]) => re.test(font.trim()));
}

/** Text in a symbol font as Unicode; null when the font is an ordinary one. */
export function mapSymbols(text: string, font: string | undefined): string | null {
  if (!font) return null;
  const table = TABLES.find(([re]) => re.test(font.trim()))?.[1];
  if (!table) return null;
  let out = "";
  for (const ch of text) {
    let cp = ch.codePointAt(0)!;
    if (cp >= 0xf000 && cp <= 0xf0ff) cp -= 0xf000;
    out += table[cp] ?? (cp >= 0x20 && cp < 0x7f && table === SYMBOL ? String.fromCharCode(cp) : cp < 0x20 ? "" : table === SYMBOL ? ch : "•");
  }
  return out;
}

/** A w:sym element's character: font plus a hex code, often in the F000 area. */
export function symChar(font: string | undefined, hex: string): string {
  const cp = parseInt(hex, 16);
  if (!Number.isFinite(cp)) return "";
  const raw = String.fromCodePoint(cp >= 0xf000 && cp <= 0xf0ff ? cp : cp);
  return mapSymbols(raw, font) ?? (cp >= 0xf000 && cp <= 0xf0ff ? String.fromCharCode(cp - 0xf000) : raw);
}
